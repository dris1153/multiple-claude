#!/bin/bash
# Builds "Claude 2" = a clone of /Applications/Claude.app with its own bundle ID and icon, always opened with
# its own data folder. macOS treats it as a different app from the original (Dock, Cmd+Tab, open/quit), and
# each app signs in to its own account. Claude Code sessions stay shared through ~/.claude/share-sessions.sh.
# Safe to re-run any time; the app launcher calls this script again when Claude.app updates.
#   build-claude2.sh [app path] [data folder]
# Another app: build-claude2.sh "/Applications/Claude 3.app" (the trailing number picks the bundle ID,
# the data folder claude<N> and the icon claude<N>.car/.icns; without an icon the original icon is used).
set -euo pipefail

SRC=/Applications/Claude.app
DEST="${1:-/Applications/Claude 2.app}"
NAME="$(basename "$DEST" .app)"
N="${NAME##* }"
DATA="${2:-$HOME/.claude-instances/claude$N}"
ID=local.claude-desktop-$N
HERE="$HOME/.claude-instances"

if pgrep -f "$DEST/Contents/MacOS/Claude" >/dev/null; then
  echo "$NAME is running; quit the app and run the script again." >&2
  exit 1
fi

TMP="$(mktemp -d "$HERE/.build.XXXXXX")"
trap 'rm -rf "$TMP"' EXIT
APP="$TMP/$NAME.app"
cp -Rc "$SRC" "$APP"   # APFS clone: costs almost no extra disk space
# The provisioning profile and notarization ticket are only valid for Anthropic's original build.
rm -f "$APP/Contents/embedded.provisionprofile" "$APP/Contents/CodeResources"

PL="$APP/Contents/Info.plist"
plutil -replace CFBundleIdentifier -string "$ID" "$PL"
plutil -replace CFBundleDisplayName -string "$NAME" "$PL"
plutil -replace CFBundleExecutable -string claude2-launcher "$PL"
# Icon Composer style icon, same size as the original (a legacy .icns gets shrunk and framed grey on macOS 26+).
# claude<N>.car is built from an Icon Composer .icon; see docs/how-it-works.md to regenerate it.
if [ -f "$HERE/claude$N.car" ]; then
  cp "$HERE/claude$N.car" "$APP/Contents/Resources/Assets.car"
  plutil -replace CFBundleIconName -string "claude$N" "$PL"
else
  plutil -remove CFBundleIconName "$PL"   # drop the Assets.car icon so macOS falls back to electron.icns
fi
[ -f "$HERE/claude$N.icns" ] && cp "$HERE/claude$N.icns" "$APP/Contents/Resources/electron.icns"
# Keep CFBundleName "Claude": Electron looks up "<CFBundleName> Helper.app" by that name.

# Dock/Finder run this launcher instead of Claude itself, so the app always gets --user-data-dir.
L="$APP/Contents/MacOS/claude2-launcher"
cat >"$L" <<'EOF'
#!/bin/sh
# Generated by __HERE__/build-claude2.sh; edit that file instead (a rebuild overwrites this one).
DATA="__DATA__"
APP="$(cd "$(dirname "$0")/../.." && pwd)"
# Two processes writing one data folder corrupt it.
if pgrep -f -- "--user-data-dir=$DATA( |\$)" >/dev/null; then   # anchored: claude2 must not match claude20
  osascript -e 'display alert "__NAME__" message "Another Claude window is already using the data of __NAME__. Quit that window (Cmd+Q) and open it again."' >/dev/null 2>&1
  exit 1
fi
v() { /usr/libexec/PlistBuddy -c "Print :CFBundleVersion" "$1/Contents/Info.plist" 2>/dev/null; }
# Claude.app just updated itself -> rebuild the clone at the same version before opening.
if [ -n "$(v /Applications/Claude.app)" ] && [ "$(v /Applications/Claude.app)" != "$(v "$APP")" ]; then
  "__HERE__/build-claude2.sh" "$APP" "$DATA" >>"__HERE__/build-claude2.log" 2>&1
fi
"$HOME/.claude/share-sessions.sh" >/dev/null 2>&1   # pull in the latest Code sessions from the other apps
# macOS does not let this app read Chrome data, so on launch it thinks the extension is missing and deletes
# the original app's Claude in Chrome manifest. Block deletion (overwrite still allowed). Undo: chmod -a "everyone deny delete" <file>
M="$HOME/Library/Application Support/Google/Chrome/NativeMessagingHosts/com.anthropic.claude_browser_extension.json"
[ -f "$M" ] && { chmod -a "everyone deny delete" "$M" 2>/dev/null; chmod +a "everyone deny delete" "$M"; }
# On launch the app grabs claude:// links (MCP sign-in callbacks, magic links). __HERE__/claude-url-router.sh
# owns those links and hands them to the Claude app used last, so nothing to do here.
exec "$APP/Contents/MacOS/Claude" --user-data-dir="$DATA" "$@"
EOF
sed -i '' -e "s#__DATA__#$DATA#g" -e "s#__HERE__#$HERE#g" -e "s#__NAME__#$NAME#g" "$L"
chmod +x "$L"

# After every file is copied: icon files brought from another machine (AirDrop, download) carry the quarantine
# flag, and macOS refuses to open the app if it stays.
xattr -cr "$APP"

# Re-sign. With an "Apple Development" certificate (Xcode > Settings > Accounts) the signature stays stable
# across builds and macOS stops re-asking for keychain/folder access. Without one, sign ad hoc.
SIGN="$(security find-identity -v -p codesigning | awk -F'"' '/Apple Development/ {print $2; exit}')"
SIGN="${SIGN:--}"
# Drop the 3 entitlements that only work with Anthropic's provisioning profile; macOS kills the app otherwise.
ENT="$TMP/entitlements.plist"
codesign -d --entitlements - --xml "$SRC" 2>/dev/null | plutil -convert xml1 -o "$ENT" -
for k in com.apple.application-identifier com.apple.developer.team-identifier keychain-access-groups; do
  /usr/libexec/PlistBuddy -c "Delete :$k" "$ENT" 2>/dev/null || true
done
for f in "$APP"/Contents/Frameworks/* "$APP"/Contents/Helpers/*; do
  codesign --force --deep --timestamp=none --sign "$SIGN" --preserve-metadata=entitlements "$f"
done
codesign --force --timestamp=none --sign "$SIGN" --identifier "$ID" --entitlements "$ENT" "$APP/Contents/MacOS/Claude"
codesign --force --timestamp=none --sign "$SIGN" --identifier "$ID" --entitlements "$ENT" "$APP"
codesign --verify --deep --strict "$APP"

# The clone's updater would download a new version and then discard it for the wrong signature. A file in place
# of its download folder stops it before downloading. The clone follows Claude.app's version via the launcher.
B="$HOME/Library/Caches/$ID.ShipIt"
[ -d "$B" ] && rm -rf "$B"
touch "$B"

if [ -e "$DEST" ]; then
  if [ "$(/usr/libexec/PlistBuddy -c 'Print :CFBundleIdentifier' "$DEST/Contents/Info.plist" 2>/dev/null)" = "$ID" ]; then
    rm -rf "$DEST"   # an older clone built by this script
  else
    mv "$DEST" "$HOME/.Trash/$NAME old-$(date +%Y%m%d-%H%M%S).app"
  fi
fi
mv "$APP" "$DEST"
/System/Library/Frameworks/CoreServices.framework/Frameworks/LaunchServices.framework/Support/lsregister -f "$DEST"
echo "Done: $DEST (data: $DATA)"
